"""Deterministic mock AI provider (the default; no network, no credentials).

Outputs are chosen by a pluggable rule table evaluated against the prompt
(task and incident ``context``). The first matching rule produces the raw
output; when no rule matches, RCA requests get a generic evidence-based report
built from the stack trace's top frame and any other schema gets a generic
schema-valid output synthesised from the incident data, except repair (patch)
requests, which raise ``NoPatchAvailable``. The same input always yields the
same output.
"""

import enum
import types
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any, Literal, Union, get_args, get_origin

from pydantic import BaseModel, ValidationError

from app.ai.base import (
    AIProvider,
    AIResult,
    NoPatchAvailable,
    Prompt,
    StructuredOutputError,
    T,
    Usage,
)

MOCK_MODEL = "sentinel-mock-1"


@dataclass(frozen=True)
class MockRule:
    """A deterministic response rule.

    ``matches`` decides whether the rule applies to a prompt/schema pair and
    ``respond`` returns the raw output (a dict or a model instance), which is
    always validated against the requested schema.
    """

    name: str
    matches: Callable[[Prompt, type[BaseModel]], bool]
    respond: Callable[[Prompt, type[BaseModel]], dict[str, Any] | BaseModel]


def _incident_label(prompt: Prompt) -> str:
    ctx = prompt.context
    exc_type = str(ctx.get("exception_type") or "UnknownError")
    message = str(ctx.get("message") or "").strip()
    label = f"{exc_type}: {message}" if message else exc_type
    return label[:200]


def _synthesise(annotation: Any, field_name: str, prompt: Prompt, depth: int) -> Any:
    if depth > 6:
        return None
    origin = get_origin(annotation)
    args = get_args(annotation)

    if origin in (Union, types.UnionType):
        if type(None) in args:
            return None
        return _synthesise(args[0], field_name, prompt, depth)
    if origin is Literal:
        return args[0]
    if origin in (list, set, frozenset, tuple):
        return []
    if origin is dict:
        return {}
    if isinstance(annotation, type):
        if issubclass(annotation, BaseModel):
            return _synthesise_model(annotation, prompt, depth + 1)
        if issubclass(annotation, enum.Enum):
            return next(iter(annotation)).value
        if issubclass(annotation, bool):
            return False
        if issubclass(annotation, int):
            return 0
        if issubclass(annotation, float):
            return 0.0
        if issubclass(annotation, str):
            return f"[mock] {field_name.replace('_', ' ')} for {_incident_label(prompt)}"
    return None


def _synthesise_model(schema: type[BaseModel], prompt: Prompt, depth: int = 0) -> dict[str, Any]:
    data: dict[str, Any] = {}
    for name, info in schema.model_fields.items():
        if not info.is_required():
            continue
        data[info.alias or name] = _synthesise(info.annotation, name, prompt, depth)
    return data


_RCA_FIELDS = {"summary", "hypotheses", "suspect_locations", "uncertainties", "next_steps"}


def _is_rca_request(prompt: Prompt, schema: type[BaseModel]) -> bool:
    return prompt.task == "rca" and _RCA_FIELDS.issubset(schema.model_fields)


def _rca_output(prompt: Prompt) -> dict[str, Any]:
    """Generic, evidence-based RCA built from the stack trace's top frame."""
    ctx = prompt.context
    label = _incident_label(prompt)
    exc_type = str(ctx.get("exception_type") or "UnknownError")
    count = ctx.get("event_count")
    frame = ctx.get("top_frame") or {}
    file = frame.get("file")
    function = frame.get("function") or None
    line = frame.get("line")
    evidence = [f"Exception reported: {label}"]
    if count:
        evidence.append(f"Observed in {count} event(s) grouped under the same fingerprint")
    uncertainties = [
        "Generated by the deterministic mock provider: no model reasoning was performed.",
        "The root cause is not confirmed until a repair verified by tests supports it.",
    ]

    if file:
        where = f"{function} ({file})" if function else file
        evidence.insert(0, f"Top stack frame: {file}:{line or '?'} in {function or '?'}")
        hypothesis = {
            "title": f"{exc_type} originates in {where}",
            "description": (
                f"The innermost application frame of the stack trace is {where}. The "
                f"code there likely does not handle the input that triggers {exc_type}."
            ),
            "confidence": 0.6,
            "evidence": evidence,
            "status": "hypothesis",
        }
        suspects = [
            {"file": file, "function": function, "reason": "Top frame of the stack trace"}
        ]
        for other in ctx.get("relevant_files") or []:
            if other != file:
                suspects.append(
                    {"file": other, "function": None, "reason": "Appears in the stack trace"}
                )
        steps = [
            f"Review {where} for unhandled inputs that raise {exc_type}.",
            "Write a regression test reproducing the failing input.",
        ]
    else:
        uncertainties.append("No stack frame could be mapped to the repository.")
        hypothesis = {
            "title": f"Unhandled {exc_type}",
            "description": f"The application raised {exc_type}; its origin in code is unknown.",
            "confidence": 0.2,
            "evidence": evidence,
            "status": "hypothesis",
        }
        suspects = []
        steps = ["Collect a stack trace with application frames to locate the failing code."]

    return {
        "summary": f"[mock] Likely cause of {label}: {hypothesis['title']} (unconfirmed).",
        "hypotheses": [hypothesis],
        "suspect_locations": suspects,
        "uncertainties": uncertainties,
        "next_steps": steps,
    }


_PATCH_FIELDS = {"files", "unified_diff", "explanation"}


def _is_patch_request(prompt: Prompt, schema: type[BaseModel]) -> bool:
    return prompt.task == "repair" and _PATCH_FIELDS.issubset(schema.model_fields)


class MockProvider(AIProvider):
    """Clearly labelled deterministic provider. Usage is always "not available".

    Without explicit ``rules`` it uses the default table of
    ``app.ai.mock_rules`` (the demo application's faults). Repair requests that
    no rule matches raise ``NoPatchAvailable`` (``no_patch_available``).
    """

    name = "mock"
    is_mock = True

    def __init__(self, rules: list[MockRule] | None = None) -> None:
        if rules is None:
            # Imported lazily: the rules depend on the repo tools and patch models.
            from app.ai.mock_rules import default_rules

            rules = default_rules()
        self._rules: list[MockRule] = list(rules)

    @property
    def rules(self) -> tuple[MockRule, ...]:
        return tuple(self._rules)

    def add_rule(self, rule: MockRule) -> None:
        self._rules.append(rule)

    def generate_structured(self, prompt: Prompt, schema: type[T]) -> AIResult[T]:
        raw: dict[str, Any] | BaseModel | None = None
        for rule in self._rules:
            if rule.matches(prompt, schema):
                raw = rule.respond(prompt, schema)
                break
        if raw is None and _is_rca_request(prompt, schema):
            raw = _rca_output(prompt)
        if raw is None and _is_patch_request(prompt, schema):
            label = _incident_label(prompt)
            raise NoPatchAvailable(f"the mock provider has no patch for this incident ({label})")
        if raw is None:
            raw = _synthesise_model(schema, prompt)
        if isinstance(raw, BaseModel):
            raw = raw.model_dump(mode="json")
        try:
            output = schema.model_validate(raw)
        except ValidationError as exc:
            raise StructuredOutputError(
                f"mock output does not match schema {schema.__name__}: {exc}"
            ) from exc
        return AIResult(output=output, usage=Usage(), provider=self.name, model=MOCK_MODEL)
